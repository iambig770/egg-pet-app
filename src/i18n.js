// 기기 언어 감지 → 지원 언어면 그대로, 아니면 'ko'
export function detectLang() {
  const nav = navigator.language?.slice(0, 2)
  return ['ko', 'en', 'zh', 'ja'].includes(nav) ? nav : 'ko'
}